class StockInfo:
    """股票档案：申万行业 1/2/3 级分类 + 名称"""

    def __init__(self):
        self._df: Optional[pd.DataFrame] = None

    @property
    def df(self) -> pd.DataFrame:
        if self._df is None:
            if os.path.exists(CACHE_FILE):
                self._df = pd.read_parquet(CACHE_FILE)
            else:
                self._df = pd.DataFrame(
                    columns=["代码", "名称", "申万1级", "申万2级", "申万3级"]
                )
        return self._df

    def _save(self):
        if self._df is not None:
            os.makedirs(os.path.dirname(CACHE_FILE), exist_ok=True)
            self._df.to_parquet(CACHE_FILE, index=False)

    # ========== 构建 ==========

    def build(self, force: bool = False):
        """
        完整构建股票档案缓存

        数据流：
          1. 下载 StockClassifyUse_stock.xls (个股→6位行业代码)
          2. 取每只股票最新行业代码
          3. 通过 SW2021_MAP 查询行业名称
          4. 与 spot 列表合并，保存 parquet
        """
        if not force and len(self.df) > 1000:
            print("缓存已存在，使用 force=True 强制重建")
            return self

        print("构建股票档案缓存...")

        # ---- 1. 下载/读取 Excel ----
        print("  下载申万行业分类 Excel...")
        xls_path = _download_sw_excel()
        df_xls = pd.read_excel(xls_path)
        print(f"  {len(df_xls)} 条分类记录")

        # ---- 2. 获取最新分类 ----
        df_xls["code_str"] = df_xls["股票代码"].astype(str).str.zfill(6)
        latest = (
            df_xls.sort_values("计入日期")
            .groupby("code_str")
            .tail(1)
            .drop_duplicates(subset="code_str", keep="last")
        )

        # ---- 3. 查询行业名称 ----
        info_map = {}
        for _, row in latest.iterrows():
            try:
                raw_code = row["code_str"]
                industry_code = str(row["行业代码"]).zfill(6)
                l1, l2, l3 = _lookup_industry(industry_code)
                code = _convert_code(raw_code)
                info_map[code] = {
                    "申万1级": l1,
                    "申万2级": l2,
                    "申万3级": l3,
                    "industry_code": industry_code,
                }
            except Exception:
                continue

        mapped = len(info_map)
        print(f"  行业映射: {mapped} 只股票")
        # 检查覆盖情况
        unmapped_codes = set()
        for _, row in latest.iterrows():
            c = str(row["行业代码"]).zfill(6)
            if c not in SW2021_MAP:
                unmapped_codes.add(c[:2])
        if unmapped_codes:
            print(f"  缺少名称映射的行业前缀: {sorted(unmapped_codes)}")

        # ---- 4. 与 spot 列表合并 ----
        print("  合并全市场股票列表...")
        try:
            spot = ak.stock_zh_a_spot_tx()[["code", "name"]]
            spot.columns = ["代码", "名称"]
        except Exception:
            spot = pd.DataFrame(columns=["代码", "名称"])

        records = []
        for _, s in spot.iterrows():
            code = s["代码"]
            info = info_map.get(code, {})
            records.append({
                "代码": code,
                "名称": info.get("名称") or s["名称"],
                "申万1级": info.get("申万1级", ""),
                "申万2级": info.get("申万2级", ""),
                "申万3级": info.get("申万3级", ""),
            })

        self._df = pd.DataFrame(records)
        self._save()

        # ---- 5. 统计 ----
        total = len(self._df)
        for col in ["申万1级", "申万2级", "申万3级"]:
            cnt = (self._df[col] != "").sum()
            uni = self._df[col].nunique()
            print(f"  {col}: {cnt} 只, {uni} 个唯一值")

        return self

    # ========== 查询 ==========

    def get(self, code: str) -> dict:
        row = self.df[self.df["代码"] == code]
        if len(row) == 0:
            return {"申万1级": "", "申万2级": "", "申万3级": "", "名称": ""}
        return row.iloc[0].to_dict()

    def get_name(self, code: str) -> str:
        row = self.df[self.df["代码"] == code]
        return row.iloc[0]["名称"] if len(row) > 0 else ""

    def all_sectors(self, level: int = 1) -> List[str]:
        col = f"申万{level}级"
        return sorted(self.df[col].dropna().replace("", pd.NA).dropna().unique())

    def stocks_in_sector(self, sector: str, level: int = 1) -> pd.DataFrame:
        col = f"申万{level}级"
        return self.df[self.df[col] == sector]

    def merge(self, df: pd.DataFrame, on: str = "代码") -> pd.DataFrame:
        return df.merge(
            self.df[["代码", "名称", "申万1级", "申万2级", "申万3级"]],
            on=on, how="left", suffixes=("", "_info"),
        )

    def update(self):
        if len(self.df) == 0:
            self.build()
        return self


def _download_sw_excel() -> str:
    """下载申万行业分类 Excel 文件"""
    import tempfile
    tmp = os.path.join(tempfile.gettempdir(), "sw_class.xls")

    # 如果已有缓存且是今天下载的，直接复用
    if os.path.exists(tmp):
        mtime = os.path.getmtime(tmp)
        if time.time() - mtime < 86400:
            return tmp

    url = "https://www.swsresearch.com/swindex/pdf/SwClass2021/StockClassifyUse_stock.xls"
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                      "(KHTML, like Gecko) Chrome/114.0.0.0 Safari/537.36"
    }
    # 使用 session 处理 SSL
    import urllib3
    urllib3.disable_warnings()
    session = requests.Session()
    session.verify = False
    r = session.get(url, headers=headers, timeout=30)
    if r.status_code == 200:
        with open(tmp, "wb") as f:
            f.write(r.content)
        return tmp
    raise RuntimeError(f"下载失败: HTTP {r.status_code}")


