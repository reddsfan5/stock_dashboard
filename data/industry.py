def _lookup_industry(code_6: str) -> tuple:
    """
    根据6位行业代码查询 (1级名称, 2级名称, 3级名称)
    优先精确匹配，其次从代码结构推导
    """
    # 精确匹配
    if code_6 in SW2021_MAP:
        return SW2021_MAP[code_6]

    l1 = _PREFIX_TO_L1.get(code_6[:2], "")
    l2_code = code_6[:4]
    # 用4位代码查找同级命名模式
    # 查找同2级下的3级条目，推断2级名称
    l2_name = ""
    l3_name = ""
    for k, v in SW2021_MAP.items():
        if k[:4] == l2_code:
            l2_name = v[1]  # 从第一个匹配项取2级名称
            if k == code_6:
                l3_name = v[2]
            elif not l3_name:
                pass
    if not l2_name and l1:
        l2_name = f"二级行业({l2_code})"
    if not l3_name:
        l3_name = f"三级行业({code_6})"

    return (l1, l2_name, l3_name)


def _convert_code(raw: str) -> str:
    """股票代码转换: 600519 → sh600519 / 000001 → sz000001 / 920045 → bj920045"""
    raw = str(int(raw)).zfill(6)
    if raw.startswith("6"):
        return "sh" + raw
    elif raw.startswith(("8", "9")):
        return "bj" + raw
    else:
        return "sz" + raw


